import test from "node:test";
import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {mkdir,readFile,rm} from "node:fs/promises";
import {dirname,join} from "node:path";
import {signin} from "./fixture.mjs";
import {setup} from "./recovery-fixture.mjs";
const require=createRequire(new URL("../../session/package.json",import.meta.url)),Y=require("yjs");

test("hosted journal recovery restores a dirty buffer over its saved file and survives a second restart",async t=>{
 const host=await setup(t),user=await signin(host.cloud.fetch),workspace=await host.workspace(user),client=await workspace.connect();
 const baseline=await client.request("fs.write",{path:"main.hx",data:"saved 🦊\n"});assert.equal(baseline.ok,true);
 const peer=new Y.Doc();Y.applyUpdate(peer,Buffer.from((await client.request("doc.open",{path:"main.hx"})).update,"base64"));
 assert.equal((await client.request("doc.save",{path:"main.hx"})).ok,true);
 let vector=Y.encodeStateVector(peer);peer.getText("text").insert(0,"unsaved ");
 const update=await client.request("doc.update",{path:"main.hx",update:Buffer.from(Y.encodeStateAsUpdate(peer,vector)).toString("base64")});assert.equal(update.ok,true);
 const record=(await workspace.control("journal",{id:update.durableUpdate.id})).body,source=record.manifest.source;
 const plan=(await workspace.control("recovery/plan",{source})).body;
 const file=await workspace.control("recovery/file",{source,mutation:baseline.recoveryMutation.id,revision:plan.revision});assert.equal(file.status,200);
 await host.stop();await rm(host.root,{recursive:true});await rm(join(dirname(host.root),"state"),{recursive:true});await host.restartCloud();
 const retained=(await workspace.control("journal",{id:update.durableUpdate.id})).body;assert.deepEqual(retained.checkpoint,record.checkpoint);
 await mkdir(host.root);await host.start("replacement");
 const control=await host.direct();assert.equal(control.hello.bufferedRestore,1);
 assert.equal((await control.request("fs.write",{path:"main.hx",data:file.body.data,encoding:"base64"})).ok,true);
 const restored=await control.request("doc.restore",{path:"main.hx",mode:"buffer",diskSha256:file.body.mutation.payload.sha256,checkpoint:retained.checkpoint});
 assert.equal(restored.ok,true,JSON.stringify(restored));assert.equal(restored.dirty,true);control.socket.close();
 const browser=await workspace.connect();const opened=await browser.request("doc.open",{path:"main.hx"});
 assert.equal(opened.text,"unsaved saved 🦊\n");assert.equal(opened.dirty,true);assert.equal(opened.buffered,true);
 Y.applyUpdate(peer,Buffer.from(opened.update,"base64"));assert.equal(peer.getText("text").toString(),opened.text);
 assert.equal((await browser.request("doc.restore",{path:"main.hx",mode:"buffer",checkpoint:retained.checkpoint})).code,"denied");
 vector=Y.encodeStateVector(peer);peer.getText("text").insert(0,"continued ");
 assert.equal((await browser.request("doc.update",{path:"main.hx",update:Buffer.from(Y.encodeStateAsUpdate(peer,vector)).toString("base64")})).ok,true);
 assert.equal((await browser.request("doc.close",{path:"main.hx"})).ok,true);
 assert.equal(await readFile(join(host.root,"main.hx"),"utf8"),"saved 🦊\n");
 browser.socket.close();await host.stop();await host.start("replacement");
 const reopened=await workspace.connect(),again=await reopened.request("doc.open",{path:"main.hx"});
 assert.equal(again.text,"continued unsaved saved 🦊\n");assert.equal(again.dirty,true);
 assert.equal((await reopened.request("doc.save",{path:"main.hx"})).ok,true);
 assert.equal(await readFile(join(host.root,"main.hx"),"utf8"),again.text);
 assert.equal((await reopened.request("doc.open",{path:"main.hx"})).dirty,false);peer.destroy();
});
